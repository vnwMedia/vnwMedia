// Mechanical route build. Edit the original page source, then rerun this builder.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),read=file=>fs.readFileSync(path.join(root,file),'utf8');
const manifest=JSON.parse(read('wordpress/clean-urls/route-manifest.json'));
const version='20261019-clean-urls',lookup={},owners=new Map(manifest.routes.map(r=>[r.path,r.source]));
for(const {source,path:route}of manifest.routes)lookup[source]=route;
for(const [source,target]of Object.entries({...manifest.aliases,...Object.fromEntries(manifest.records.filter(r=>r.type==='redirect').map(r=>[r.source,r.target]))})){
 const [file,fragment]=target.split('#');if(lookup[file]!==undefined)lookup[source]=lookup[file]+(fragment?'#'+fragment:'');
}
for(const [source,target]of Object.entries({...lookup})){
 const clean=source==='index.html'?'':source.endsWith('/index.html')?source.slice(0,-10):source.slice(0,-5)+'/';
 if(!owners.has(clean))lookup[clean.replace(/\/$/,'')]=target;
}
for(const [route]of owners)lookup[route.replace(/\/$/,'')]=route;
const clientModule=read('wordpress/clean-urls/clean-urls.js');
fs.writeFileSync(path.join(root,'site-clean-urls.js'),`// Generated by scripts/build-clean-url-preview.cjs; no lead data or cookies.\nif(location.protocol!=='file:'){window.vnwCleanRoutes={home:new URL('.',document.currentScript.src).href,redirectLegacy:true,routes:${JSON.stringify(lookup)}};}\n`+clientModule);
const generated=[],sourcePages=[];
for(const {source,path:route}of manifest.routes){
 assert(fs.existsSync(path.join(root,source)),'approved source exists: '+source);
 let html=read(source),prefix='../'.repeat(source.split('/').length-1);
 html=html.replace(/<script\b[^>]*src="[^\"]*site-clean-urls\.js[^\"]*"[^>]*><\/script>\s*/g,'');
 const canonical='https://vnwmedia.github.io/vnwMedia/'+route;
 html=html.replace(/(<link\b[^>]*rel="canonical"[^>]*href=")[^"]*(")/gi,'$1'+canonical+'$2');
 html=html.replace(/(<meta\b[^>]*property="og:url"[^>]*content=")[^"]*(")/gi,'$1'+canonical+'$2');
 html=html.replace(/(<script\b[^>]*type="application\/ld\+json"[^>]*>)([\s\S]*?)(<\/script>)/gi,(_,open,json,close)=>open+json.replace(/https:\/\/vnwmedia\.github\.io\/vnwMedia\/[^"\s<>\\]*/g,value=>{
  const url=new URL(value),key=url.pathname.slice('/vnwMedia/'.length).replace(/\/$/,'');
  if(lookup[key]===undefined)return value;
  return 'https://vnwmedia.github.io/vnwMedia/'+lookup[key]+url.search+url.hash;
 })+close);
 html=html.replace('</head>',`<script defer src="${prefix}site-clean-urls.js?v=${version}"></script></head>`);
 fs.writeFileSync(path.join(root,source),html);sourcePages.push(source);
 const output=route?route+'index.html':'index.html';
 if(output===source)continue;
 assert(!manifest.routes.some(r=>r.source===output),'never overwrite an existing approved page: '+output);
 const base=path.posix.relative(path.posix.dirname(output),path.posix.dirname(source))+'/';
 const copy=html.replace(/(<head\b[^>]*>)/i,`$1<base href="${base}"><meta name="vnw-clean-source" content="${source}">`);
 fs.mkdirSync(path.join(root,path.posix.dirname(output)),{recursive:true});fs.writeFileSync(path.join(root,output),copy);generated.push({source,output,base});
}
// The preview's sitemap must point to working clean preview URLs, not WordPress.
fs.writeFileSync(path.join(root,'sitemap.xml'),read('wordpress/clean-urls/sitemap.xml').replaceAll('https://vnwmedia.net/','https://vnwmedia.github.io/vnwMedia/'));
fs.writeFileSync(path.join(root,'reports/clean-url-preview-build.json'),JSON.stringify({version,source_pages:sourcePages,generated,routes:manifest.routes,lookup},null,2)+'\n');
console.log(`Prepared ${manifest.routes.length} distinct clean preview pages; ${generated.length} generated directory indexes; source files retained as legacy compatibility routes.`);
